import {
  domainListSchema,
  emailSchema,
  panelUserSchema,
  personNameSchema,
  timezoneSchema,
  userRoleSchema,
  userStatusSchema,
} from "../../validate/schemas.ts";
import { ADDS, READ_ONLY, annotate, defineTool, opt, optional, req, secret, type ToolSpec } from "../define.ts";

const userName = panelUserSchema.describe("CloudPanel login name, for example john.doe.");

export const userTools: ToolSpec[] = [
  defineTool({
    name: "clp_user_list",
    kind: "clpctl",
    command: "user:list",
    cls: "read",
    title: "List the CloudPanel users",
    summary: "Lists all CloudPanel panel users (clpctl user:list; CloudPanel 2.3.0 and later): user name, name, e-mail, role, status.",
    shape: {},
    annotations: READ_ONLY,
    options: {},
    plan: () => ({
      command: "user:list",
      options: [],
      flags: [],
      summary: "List the CloudPanel users",
      effects: [],
      undo: "nothing to undo",
      protect: [],
    }),
  }),
  defineTool({
    name: "clp_user_add",
    kind: "clpctl",
    command: "user:add",
    cls: "admin",
    title: "Add a CloudPanel user",
    summary:
      "Adds a CloudPanel panel user (clpctl user:add, CloudPanel 2.3.0 and later). Roles: admin (everything), site-manager (all sites, no admin area), user (only the listed sites).",
    generatesPassword: true,
    shape: {
      userName,
      email: emailSchema,
      firstName: personNameSchema,
      lastName: personNameSchema,
      role: userRoleSchema,
      sites: domainListSchema.optional().describe("Sites the user may access. Only for role user; refused for other roles."),
      timezone: timezoneSchema.describe("For example UTC or Africa/Casablanca."),
      status: userStatusSchema.describe("1 = active (the docs' example); 0 = inactive."),
    },
    annotations: ADDS,
    options: {
      userName: req("panelUser"),
      email: req("email"),
      firstName: req("person"),
      lastName: req("person"),
      password: req("password"),
      role: req("role"),
      sites: optional("domainList"),
      timezone: req("timezone"),
      status: req("status"),
    },
    protectOptions: { userName: "panelUser", sites: "domain" },
    check: (a) =>
      a["sites"] !== undefined && a["role"] !== "user" ? "sites can only be set when role is user" : null,
    plan: (a) => ({
      command: "user:add",
      options: [
        opt("userName", a.userName),
        opt("email", a.email),
        opt("firstName", a.firstName),
        opt("lastName", a.lastName),
        secret("password", "panel-user", a.userName, a.userName),
        opt("role", a.role),
        ...(a.sites === undefined ? [] : [opt("sites", a.sites.join(","))]),
        opt("timezone", a.timezone),
        opt("status", a.status),
      ],
      flags: [],
      summary: `Add the panel user ${a.userName} (${a.email}) with role ${a.role}`,
      effects: [
        a.role === "admin" ? "creates a panel ADMINISTRATOR with access to everything" : `creates a panel user with role ${a.role}`,
        "generates a password, saved in a file on your machine and never shown",
      ],
      undo: "clp_user_delete removes the user",
      confirm: { target: a.userName, noun: "user name" },
      protect: [
        { kind: "panelUser", value: a.userName },
        ...(a.sites ?? []).map((value) => ({ kind: "domain" as const, value })),
      ],
    }),
  }),
  defineTool({
    name: "clp_user_delete",
    kind: "clpctl",
    command: "user:delete",
    cls: "admin",
    title: "Delete a CloudPanel user",
    summary: "Deletes a CloudPanel panel user (clpctl user:delete --force, CloudPanel 2.3.0 and later). --force is passed because no terminal exists to answer clpctl's yes/no question (without it clpctl asks, gets no answer, does nothing and still exits 0); the human's typed confirmation is the protection. Protected users cannot be deleted through this server.",
    shape: { userName },
    annotations: annotate(false, true, true),
    options: { userName: req("panelUser") },
    flags: ["--force"],
    protectOptions: { userName: "panelUser" },
    plan: (a) => ({
      command: "user:delete",
      options: [opt("userName", a.userName)],
      // observed on CloudPanel 2.5.4: without --force the question gets no answer and nothing is done (exit status 0)
      flags: ["--force"],
      summary: `DELETE the panel user ${a.userName}`,
      effects: [`the user ${a.userName} can no longer log in to CloudPanel`],
      undo: "re-create the user with clp_user_add (settings and password are lost)",
      confirm: { target: a.userName, noun: "user name" },
      protect: [{ kind: "panelUser", value: a.userName }],
    }),
  }),
  defineTool({
    name: "clp_user_reset_password",
    kind: "clpctl",
    command: "user:reset:password",
    cls: "admin",
    title: "Reset a CloudPanel user's password",
    summary: "Resets the password of a CloudPanel panel user to a new random one (clpctl user:reset:password). The user is locked out until they get the new password from the file.",
    generatesPassword: true,
    shape: { userName },
    annotations: annotate(false, true, false),
    options: { userName: req("panelUser"), password: req("password") },
    protectOptions: { userName: "panelUser" },
    plan: (a) => ({
      command: "user:reset:password",
      options: [opt("userName", a.userName), secret("password", "panel-user", a.userName, a.userName)],
      flags: [],
      summary: `Reset the password of the panel user ${a.userName}`,
      effects: ["the old password stops working", "the new random password is saved in a file on your machine and never shown"],
      undo: "reset it again; the old password cannot be restored",
      confirm: { target: a.userName, noun: "user name" },
      protect: [{ kind: "panelUser", value: a.userName }],
    }),
  }),
  defineTool({
    name: "clp_user_disable_mfa",
    kind: "clpctl",
    command: "user:disable:mfa",
    cls: "admin",
    title: "Disable two-factor authentication for a user",
    summary: "Disables two-factor authentication for a CloudPanel panel user (clpctl user:disable:mfa). This lowers that account's security.",
    shape: { userName },
    annotations: annotate(false, false, true),
    options: { userName: req("panelUser") },
    protectOptions: { userName: "panelUser" },
    plan: (a) => ({
      command: "user:disable:mfa",
      options: [opt("userName", a.userName)],
      flags: [],
      summary: `Disable two-factor authentication for the panel user ${a.userName}`,
      effects: [`the account ${a.userName} will log in with its password only until two-factor is enabled again`],
      undo: "the user enables two-factor again in their account settings",
      confirm: { target: a.userName, noun: "user name" },
      protect: [{ kind: "panelUser", value: a.userName }],
    }),
  }),
];

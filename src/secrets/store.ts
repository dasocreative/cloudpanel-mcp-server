import { randomBytes } from "node:crypto";
import { chmodSync, linkSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ensurePrivateDir } from "../fsutil.ts";

const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
export const PASSWORD_LENGTH = 32;

/** 32 random characters from [A-Za-z0-9], uniformly (biased bytes are rejected). */
export function generatePassword(): string {
  let out = "";
  while (out.length < PASSWORD_LENGTH) {
    for (const byte of randomBytes(64)) {
      if (byte >= 248) continue; // 248 = 4 * 62: reject the tail so no symbol is likelier
      out += ALPHABET.charAt(byte % 62);
      if (out.length === PASSWORD_LENGTH) break;
    }
  }
  return out;
}

export type SecretKind = "site" | "db" | "panel-user" | "basic-auth" | "master-db";

export interface SecretRequest {
  readonly kind: SecretKind;
  /** The domain, database or user the password belongs to. Part of the file name. */
  readonly target: string;
  /** The account that has the password (site user, database user, ...). */
  readonly account: string;
  /** The clpctl option the password goes into, or "output" for a captured one. */
  readonly option: string;
}

export class SecretsError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "SecretsError";
  }
}

export interface CaptureRequest {
  readonly kind: SecretKind;
  readonly target: string;
}

export interface Reservation {
  /** Where the secret file is now. */
  readonly path: string;
  /** Called after the command ran. Returns the final path (renamed when the command failed). */
  commit(ok: boolean): string;
  /** The command never ran: remove the file. */
  discard(): void;
}

/** A file-name component: no slash, not "." or "..", nothing but letters, digits, ".", "_", "-", "*". */
const SAFE_NAME = /^(?!\.{1,2}$)[A-Za-z0-9._-]{1,128}$/;

/**
 * <state>/secrets/<profile>/<kind>-<target>-<time>-<rand>.json, directory mode 700, file mode 600.
 * The file is written BEFORE the command runs (so a password can never be lost) with the
 * exclusive-create flag, so an existing file is never overwritten; every file name is unique.
 */
export class SecretsStore {
  readonly dir: string;
  private readonly stateDir: string;
  private readonly profile: string;
  private readonly now: () => Date;
  private readonly suffix: () => string;

  constructor(
    stateDir: string,
    profile: string,
    now: () => Date = () => new Date(),
    /** Tests inject a fixed value to force a name collision. */
    suffix: () => string = () => randomBytes(3).toString("hex"),
  ) {
    this.stateDir = stateDir;
    this.profile = profile;
    this.dir = join(stateDir, "secrets", profile);
    this.now = now;
    this.suffix = suffix;
  }

  reserve(request: SecretRequest, password: string, command: string): Reservation {
    if (!SAFE_NAME.test(request.kind) || !SAFE_NAME.test(request.target) || !SAFE_NAME.test(this.profile)) {
      throw new SecretsError("the secret's target is not usable as a file name, so nothing is run");
    }
    ensurePrivateDir(this.stateDir);
    ensurePrivateDir(join(this.stateDir, "secrets"));
    ensurePrivateDir(this.dir);
    const stamp = this.now().toISOString().replace(/[-:.]/g, "");
    const base = `${request.kind}-${request.target}-${stamp}-${this.suffix()}`;
    const path = join(this.dir, `${base}.json`);
    const body = {
      profile: this.profile,
      kind: request.kind,
      target: request.target,
      account: request.account,
      option: request.option,
      password,
      createdAt: this.now().toISOString(),
      command,
      note: "Generated by cloudpanel-mcp-server and written BEFORE the command ran. If the command failed this file is renamed to *.failed.json: the password was probably never applied. Change this password after the first login.",
    };
    try {
      writeFileSync(path, `${JSON.stringify(body, null, 2)}\n`, { flag: "wx", mode: 0o600 });
    } catch (error) {
      throw new SecretsError(`cannot write the secrets file (${(error as NodeJS.ErrnoException).code ?? "error"})`);
    }
    try {
      chmodSync(path, 0o600);
    } catch {
      // Windows
    }
    let current = path;
    return {
      get path() {
        return current;
      },
      commit: (ok: boolean): string => {
        if (ok) return current;
        const failed = join(this.dir, `${base}.failed.json`);
        linkSync(current, failed); // fails if the target exists: never overwrites
        unlinkSync(current);
        current = failed;
        return current;
      },
      discard: (): void => {
        unlinkSync(current);
      },
    };
  }

  /**
   * Writes text that came out of a command and must not be shown (for example the output of
   * db:show:master-credentials) to a new 0600 file and returns its path.
   */
  capture(request: CaptureRequest, text: string, command: string): string {
    if (!SAFE_NAME.test(request.kind) || !SAFE_NAME.test(request.target) || !SAFE_NAME.test(this.profile)) {
      throw new SecretsError("the secret's target is not usable as a file name");
    }
    ensurePrivateDir(this.stateDir);
    ensurePrivateDir(join(this.stateDir, "secrets"));
    ensurePrivateDir(this.dir);
    const stamp = this.now().toISOString().replace(/[-:.]/g, "");
    const path = join(this.dir, `${request.kind}-${request.target}-${stamp}-${this.suffix()}.json`);
    const body = {
      profile: this.profile,
      kind: request.kind,
      target: request.target,
      createdAt: this.now().toISOString(),
      command,
      output: text,
      note: "Output of a command that prints secrets, saved by cloudpanel-mcp-server and never shown to the model.",
    };
    try {
      writeFileSync(path, `${JSON.stringify(body, null, 2)}\n`, { flag: "wx", mode: 0o600 });
    } catch (error) {
      throw new SecretsError(`cannot write the secrets file (${(error as NodeJS.ErrnoException).code ?? "error"})`);
    }
    try {
      chmodSync(path, 0o600);
    } catch {
      // Windows
    }
    return path;
  }
}

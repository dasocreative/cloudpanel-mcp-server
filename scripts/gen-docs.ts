/**
 * Generates the tool reference from the catalogue, so the documentation cannot drift from the code.
 *
 *   node scripts/gen-docs.ts           write docs/TOOLS.md (and the tables between the markers in README.md, if it has them)
 *   node scripts/gen-docs.ts --check   exit 1 if either is out of date (used by the tests and CI)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildCatalog } from "../src/catalog/index.ts";
import { describeTool, type ToolSpec } from "../src/catalog/define.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TOOLS_PATH = join(ROOT, "docs", "TOOLS.md");
export const README_PATH = join(ROOT, "README.md");
export const START = "<!-- tools:start (generated by npm run gen:docs; do not edit) -->";
export const END = "<!-- tools:end -->";

const CLASS_TITLE: Record<string, string> = {
  read: "READ (always available)",
  write: "WRITE (adds or updates; a human ticks a box)",
  destructive: "DESTRUCTIVE (a human types the target's name; plan token required)",
  admin: "ADMIN (a human types the target; plan token required)",
};
const ORDER = ["read", "write", "destructive", "admin"];
const ENVELOPE = new Set(["profile", "dryRun", "planToken"]);

interface Param {
  readonly name: string;
  readonly type: string;
  readonly required: boolean;
  readonly description: string;
}

function params(spec: ToolSpec): Param[] {
  const d = describeTool(spec, ["name"], "name");
  const props = (d.inputSchema["properties"] ?? {}) as Record<string, Record<string, unknown>>;
  const required = new Set((d.inputSchema["required"] ?? []) as string[]);
  return Object.entries(props)
    .filter(([name]) => !ENVELOPE.has(name))
    .map(([name, schema]) => {
      let type = String(schema["type"] ?? "any");
      if (Array.isArray(schema["enum"])) type = (schema["enum"] as string[]).join(" | ");
      if (type === "array") type = `list of ${String((schema["items"] as Record<string, unknown> | undefined)?.["type"] ?? "value")}`;
      return { name, type, required: required.has(name), description: String(schema["description"] ?? "").replace(/\|/g, "\\|") };
    });
}

function approvalOf(spec: ToolSpec): string {
  if (spec.cls === "read") return "none";
  if (spec.cls === "write") return "tick box (or the client's own, with `approval.write: \"client\"`)";
  return "typed name + plan token";
}

const bySpec = (specs: ToolSpec[], cls: string): ToolSpec[] => specs.filter((s) => s.cls === cls);

function allSpecs(): ToolSpec[] {
  return buildCatalog();
}

export function readmeTables(): string {
  const specs = allSpecs();
  const out: string[] = [];
  for (const cls of ORDER) {
    const group = bySpec(specs, cls);
    if (group.length === 0) continue;
    out.push(`**${CLASS_TITLE[cls]}**`, "", "| Tool | Runs | Parameters |", "| ---- | ---- | ---------- |");
    for (const spec of group) {
      const list = params(spec).map((p) => `\`${p.name}${p.required ? "" : "?"}\``).join(", ") || "–";
      const runs = spec.command === null ? (spec.kind === "inventory" ? "unofficial inventory script" : "`clpctl` (usage listing)") : `\`${spec.command}\`${spec.kind === "siteuser" ? " as the site user" : ""}`;
      out.push(`| \`${spec.name}\` | ${runs} | ${list} |`);
    }
    out.push("");
  }
  return out.join("\n").trimEnd();
}

export function toolsDoc(): string {
  const specs = allSpecs();
  const out: string[] = [
    "# Tool reference",
    "",
    "Generated from the tool catalogue by `npm run gen:docs`; do not edit by hand. Every changing tool also takes `dryRun` and `planToken`;",
    "every tool takes `profile` when more than one server profile is configured. Output from the server (stdout, stderr, listings) is untrusted data.",
    "",
    "## Overview",
    "",
    readmeTables(),
    "",
    "Not available because CloudPanel's CLI cannot do it (use the panel): WordPress sites, PHP and Node/Python version or settings changes, cron jobs,",
    "SSH/FTP users, per-site Basic Auth, firewall, backups, the vhost editor, listing databases or certificates. [COMMAND-REFERENCE.md](COMMAND-REFERENCE.md)",
    "lists every command, option and fact with its source (the official documentation first, then what a real server showed).",
    "",
  ];
  for (const cls of ORDER) {
    const group = bySpec(specs, cls);
    if (group.length === 0) continue;
    out.push(`## ${CLASS_TITLE[cls]}`, "");
    for (const spec of group) {
      out.push(`### \`${spec.name}\``, "");
      out.push(`- **Class:** ${cls.toUpperCase()} · **Approval:** ${approvalOf(spec)} · **Runs:** ${spec.command === null ? "no clpctl command" : `\`${spec.command}\`${spec.kind === "siteuser" ? " as the site user" : ""}`}`);
      out.push(`- **Annotations:** readOnly ${spec.annotations.readOnlyHint}, destructive ${spec.annotations.destructiveHint}, idempotent ${spec.annotations.idempotentHint}, openWorld ${spec.annotations.openWorldHint}${spec.requiresUserInteraction ? " · asks on every call in Claude Code (`anthropic/requiresUserInteraction`)" : ""}`);
      out.push("", `> ${spec.description}`, "");
      const list = params(spec);
      if (list.length === 0) {
        out.push("No parameters of its own.", "");
      } else {
        out.push("| Parameter | Type | Required | Description |", "| --------- | ---- | -------- | ----------- |");
        for (const p of list) out.push(`| \`${p.name}\` | ${p.type} | ${p.required ? "yes" : "no"} | ${p.description} |`);
        out.push("");
      }
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}

export function withTables(readme: string): string {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < 0 || end < start) throw new Error("README.md lacks the tools markers");
  return `${readme.slice(0, start + START.length)}\n\n${readmeTables()}\n\n${readme.slice(end)}`;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const readme = existsSync(README_PATH) ? readFileSync(README_PATH, "utf8") : "";
  const wantedTools = toolsDoc();
  const wantedReadme = readme.includes(START) ? withTables(readme) : readme;
  if (process.argv.includes("--check")) {
    const toolsOk = existsSync(TOOLS_PATH) && readFileSync(TOOLS_PATH, "utf8") === wantedTools;
    if (!toolsOk || wantedReadme !== readme) {
      process.stderr.write("docs/TOOLS.md or the tool tables in README.md are out of date: run npm run gen:docs\n");
      process.exit(1);
    }
    process.stdout.write("generated docs are up to date\n");
  } else {
    writeFileSync(TOOLS_PATH, wantedTools);
    if (readme !== "") writeFileSync(README_PATH, wantedReadme);
    process.stdout.write("wrote docs/TOOLS.md and the README tool tables\n");
  }
}
